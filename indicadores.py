from  dataclasses import dataclass, field

@dataclass

class Indicador:
    #Titulo que aparece en el correo
    nombre: str
    #archivo dentro de la carpeta de consultas
    archivo_sql: str = ""
    #columnas numericas que retorna la consulta
    columnas: list[str] = field(default_factory=list)
    #barras o lineas
    tipo_grafico: str = ""
    #numero, moneda o porcentaje
    formato: str = "numero"
    #se dibuja en el grafico y colorea la tabla
    meta: float | None = None
    #>= mayor es mejor, <= menoe es mejor
    meta_sentido: str = ">="
    #suma, promedio o None
    acumulado: str | None = None
    descripcion: str = ""
    # (etiqueta, numerador, denominador)
    porcentaje: tuple[str, str, str] | None = None 
    # colorea la fila de porcentaje
    meta_porcentaje: float | None = None
    # True para incluir gráfico en el correo
    grafico: bool = False
    proceso: str = "General"
    tipo: str = "mensual"   # "mensual" = 12 meses | "foto" = valor al día de corte | "detalle" = solo Excel
    excel: bool = False     # True = incluir también en el Excel (para tipo mensual)
    fuente: str = "sql"
    consulta_zoho: str = ""
    sistema: str = ""  # nombre de la fuente en el archivo; vacío = según fuente



